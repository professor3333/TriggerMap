"""Descriptive statistics of the processed corpus, rendered to Markdown."""

from __future__ import annotations

from collections import Counter
from collections.abc import Sequence
from typing import Any

from triggermap.corpus.cues import CUE_GROUPS, cue_counts
from triggermap.ingest.records import AdvisoryDocument
from triggermap.text.markdown import BlockKind
from triggermap.text.preprocessing import compose_raw, preprocess


def percentiles(values: Sequence[int], qs: Sequence[float]) -> dict[str, int]:
    ordered = sorted(values)
    if not ordered:
        return {f"p{round(q * 100)}": 0 for q in qs}
    last = len(ordered) - 1
    return {f"p{round(q * 100)}": ordered[min(last, round(q * last))] for q in qs}


def corpus_stats(docs: Sequence[AdvisoryDocument]) -> dict[str, Any]:
    chars: list[int] = []
    words: list[int] = []
    sentences: list[int] = []
    structure: Counter[str] = Counter()
    cues: Counter[str] = Counter()
    years: Counter[str] = Counter()
    projects: Counter[str] = Counter()

    for doc in docs:
        pre = preprocess(compose_raw(doc.summary, doc.details))
        chars.append(len(pre.text))
        words.append(len(pre.text.split()))
        sentences.append(len(pre.sentences))
        kinds = {b.kind for b in pre.canonical.blocks}
        for kind in (BlockKind.HEADING, BlockKind.LIST_ITEM, BlockKind.CODE, BlockKind.TABLE):
            structure[kind.value] += kind in kinds
        code_blocks = {(b.start, b.end) for b in pre.canonical.blocks if b.kind is BlockKind.CODE}
        structure["inline_code"] += any(
            span not in code_blocks for span in pre.canonical.code_spans
        )
        for group, count in cue_counts(pre.text).items():
            cues[group] += count > 0
        years[doc.published[:4]] += 1
        for package in doc.pypi_packages:
            projects[package] += 1

    qs = (0.1, 0.25, 0.5, 0.75, 0.9, 0.99)
    return {
        "documents": len(docs),
        "multi_package": sum(len(d.pypi_packages) > 1 for d in docs),
        "multi_ecosystem": sum(len(d.ecosystems) > 1 for d in docs),
        "distinct_packages": len(projects),
        "published_by_year": dict(sorted(years.items())),
        "top_packages": projects.most_common(20),
        "canonical_chars": percentiles(chars, qs) | {"max": max(chars, default=0)},
        "whitespace_tokens": percentiles(words, qs) | {"max": max(words, default=0)},
        "sentences": percentiles(sentences, qs) | {"max": max(sentences, default=0)},
        "docs_over_384_words": sum(w > 384 for w in words),
        "structure_docs": dict(structure),
        "cue_group_docs": {group: cues[group] for group in CUE_GROUPS},
    }


def render_markdown(stats: dict[str, Any], manifest: dict[str, Any]) -> str:
    n = stats["documents"]

    def pct(k: int) -> str:
        return f"{k:,} ({k / n:.1%})" if n else "0"

    source = manifest["source"]
    counts = manifest["counts"]
    lines = [
        "# Corpus statistics",
        "",
        "Generated by `triggermap corpus stats`; do not edit by hand.",
        "",
        f"- Source: [{source['repository']}]({source['repository']}) at commit "
        f"`{source['commit']}` ({source['commit_date']}), path `{source['path']}`, "
        f"license {source['license']}",
        f"- Preprocessing version: `{manifest['preprocessing_version']}`",
        "",
        "## Filtering",
        "",
        "| Bucket | Files |",
        "|---|---:|",
        *(f"| {key} | {value:,} |" for key, value in counts.items()),
        "",
        "## Kept documents",
        "",
        f"- Documents: {n:,}",
        f"- Distinct PyPI packages (PEP 503): {stats['distinct_packages']:,}",
        f"- Advisories naming more than one PyPI package: {pct(stats['multi_package'])}",
        f"- Advisories also listing another ecosystem: {pct(stats['multi_ecosystem'])}",
        f"- Longer than 384 whitespace tokens: {pct(stats['docs_over_384_words'])} "
        "(subword counts will be higher; measured once a tokenizer is chosen)",
        "",
        "| Length | " + " | ".join(stats["canonical_chars"]) + " |",
        "|---|" + "---:|" * len(stats["canonical_chars"]),
    ]
    for name in ("canonical_chars", "whitespace_tokens", "sentences"):
        row = stats[name]
        lines.append(f"| {name} | " + " | ".join(f"{v:,}" for v in row.values()) + " |")
    lines += [
        "",
        "## Structure (documents containing at least one)",
        "",
        "| Element | Documents |",
        "|---|---:|",
        *(f"| {k} | {pct(v)} |" for k, v in stats["structure_docs"].items()),
        "",
        "## Condition cue groups (documents containing at least one cue)",
        "",
        "Cues are surface keywords used for sampling, not labels.",
        "",
        "| Cue group | Documents |",
        "|---|---:|",
        *(f"| {k} | {pct(v)} |" for k, v in stats["cue_group_docs"].items()),
        "",
        "## Published by year",
        "",
        "| Year | Documents |",
        "|---|---:|",
        *(f"| {y} | {c:,} |" for y, c in stats["published_by_year"].items()),
        "",
        "## Most frequent packages",
        "",
        "| Package | Advisories |",
        "|---|---:|",
        *(f"| {p} | {c:,} |" for p, c in stats["top_packages"]),
        "",
    ]
    return "\n".join(lines)
