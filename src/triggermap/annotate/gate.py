"""Pilot decision gate: projected support per role, group operator and document status.

Counts come from pilot records **outside the test split** (the locked test documents are
never read). Per-document rates are taken separately for the natural (``random``) and
``enriched`` strata and projected onto the planned gold-set composition. A class projected
below the threshold is reported **unsupported**: it stays in the label inventory and is still
annotated, but no model claims it until targeted sampling finds more examples.
"""

from __future__ import annotations

import statistics
from collections import Counter
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any

from triggermap.schema.models import (
    AdvisoryAnnotation,
    AnnotationOrigin,
    DocumentStatus,
    GroupOperator,
    Role,
)

# (group, labels, gated): document statuses are reported but not gated, because a model
# outputs NO_EXPLICIT_CONDITION whenever it finds nothing and never "claims" it as a class.
GATED: tuple[tuple[str, tuple[str, ...], bool], ...] = (
    ("Role", tuple(r.value for r in Role), True),
    ("Group operator", tuple(o.value for o in GroupOperator), True),
    ("Document status", tuple(s.value for s in DocumentStatus), False),
)


@dataclass(frozen=True)
class Plan:
    """Planned gold-set composition (docs/annotation_plan.md)."""

    natural: int = 467  # pilot random 50, batches 01/03/04, 30% of batch-05
    enriched: int = 333  # pilot enriched 50, batch-02 100, 70% of batch-05 (uncertainty)
    evaluation_natural: int = 300  # dev 150 + test 150, natural only
    threshold: int = 50


DEFAULT_PLAN = Plan()


@dataclass(frozen=True)
class Row:
    group: str
    label: str
    counts: Mapping[str, int]  # stratum -> count
    manual: int
    projected: float
    projected_evaluation: float
    supported: bool | None  # None: reported, not gated


def _tally(records: Sequence[AdvisoryAnnotation]) -> Counter[str]:
    counts: Counter[str] = Counter()
    for record in records:
        counts.update(c.role.value for c in record.conditions)
        counts.update(g.operator.value for g in record.groups)
        counts[record.document_status.value] += 1
    return counts


def gate(
    records: Sequence[AdvisoryAnnotation],
    strata: Mapping[str, str],
    assignment: Mapping[str, str],
    plan: Plan = DEFAULT_PLAN,
) -> tuple[list[Row], dict[str, int]]:
    """Rows per gated label, plus document counts per stratum (test split excluded)."""
    usable = [r for r in records if assignment.get(r.advisory_id) != "test"]
    by_stratum: dict[str, list[AdvisoryAnnotation]] = {"random": [], "enriched": []}
    for record in usable:
        by_stratum.setdefault(strata[record.advisory_id], []).append(record)
    tallies = {s: _tally(rs) for s, rs in by_stratum.items()}
    manual = _tally([r for r in usable if r.origin == AnnotationOrigin.MANUAL])
    sizes = {s: len(rs) for s, rs in by_stratum.items()}

    def rate(stratum: str, label: str) -> float:
        return tallies[stratum][label] / sizes[stratum] if sizes[stratum] else 0.0

    rows = []
    for group, labels, gated in GATED:
        for label in labels:
            projected = rate("random", label) * plan.natural + rate("enriched", label) * (
                plan.enriched
            )
            rows.append(
                Row(
                    group,
                    label,
                    {s: tallies[s][label] for s in by_stratum},
                    manual[label],
                    projected,
                    rate("random", label) * plan.evaluation_natural,
                    projected >= plan.threshold if gated else None,
                )
            )
    return rows, sizes


def render_gate(
    rows: Sequence[Row],
    sizes: Mapping[str, int],
    origins: Mapping[str, int],
    lead_times: Sequence[float],
    plan: Plan = DEFAULT_PLAN,
    source: str = "",
) -> str:
    lines = [
        "# Pilot decision gate",
        "",
        "Generated by `triggermap annotate gate`; do not edit by hand.",
        "",
        f"- Gold: {source}",
        f"- Documents counted (test split excluded): {sum(sizes.values())} "
        f"({', '.join(f'{s} {n}' for s, n in sorted(sizes.items()))})",
        f"- Origin of counted records: "
        f"{', '.join(f'{k} {v}' for k, v in sorted(origins.items())) or 'none'}",
        f"- Projection: {plan.natural} natural + {plan.enriched} enriched-like documents; "
        f"evaluation support assumes {plan.evaluation_natural} natural dev + test documents",
        f"- Threshold: a class projected below {plan.threshold} examples is **unsupported**",
        "",
        "| Group | Label | Random | Enriched | Manual only | Projected (800) "
        "| Projected in dev + test | Status |",
        "|---|---|---:|---:|---:|---:|---:|---|",
    ]
    for row in rows:
        if row.supported is None:
            status = "reported, not gated"
        else:
            status = "supported" if row.supported else "**unsupported**"
        if row.supported is not False and row.projected_evaluation < 1:
            status += " · no natural evaluation support"
        lines.append(
            f"| {row.group} | {row.label} | {row.counts.get('random', 0)} "
            f"| {row.counts.get('enriched', 0)} | {row.manual} | {row.projected:.0f} "
            f"| {row.projected_evaluation:.0f} | {status} |"
        )
    lines += ["", "## Pace", ""]
    if lead_times:
        minutes = [t / 60 for t in lead_times]
        median = statistics.median(minutes)
        lines += [
            f"- Timed documents: {len(minutes)} (Label Studio lead time; manual records only)",
            f"- Median minutes per document: {median:.1f}",
            f"- Projected hours for {plan.natural + plan.enriched} documents at the median: "
            f"{median * (plan.natural + plan.enriched) / 60:.0f}",
        ]
    else:
        lines.append("No lead times recorded.")
    lines.append("")
    return "\n".join(lines)


def strata_of(sample: Mapping[str, Any]) -> dict[str, str]:
    return {str(item["advisory_id"]): str(item["stratum"]) for item in sample["items"]}
