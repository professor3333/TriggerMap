"""Import a Label Studio export: validate, write clean records, report problems and pace."""

from __future__ import annotations

import json
import statistics
from collections import Counter
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from triggermap.annotate.label_studio import Conversion, convert_task
from triggermap.ingest.records import AdvisoryDocument


def import_export(
    tasks: Sequence[Mapping[str, Any]],
    corpus: Mapping[str, AdvisoryDocument],
    annotation_version: str,
    annotator: str,
) -> list[Conversion]:
    conversions = [convert_task(t, corpus, annotation_version, annotator) for t in tasks]
    return sorted(conversions, key=lambda c: c.advisory_id)


def write_records(conversions: Sequence[Conversion], path: Path) -> int:
    """Write only records without issues; return how many were written."""
    path.parent.mkdir(parents=True, exist_ok=True)
    written = 0
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        for conv in conversions:
            if conv.record is not None and not conv.issues:
                fh.write(conv.record.model_dump_json(exclude_none=True))
                fh.write("\n")
                written += 1
    return written


def render_report(
    conversions: Sequence[Conversion],
    pilot_items: Mapping[str, Mapping[str, Any]],
    written: int,
) -> str:
    lines = [
        "# Annotation import report",
        "",
        "Generated by `triggermap annotate import`; do not edit by hand.",
        "",
        f"- Tasks in export: {len(conversions)}",
        f"- Records written (no issues): {written}",
        f"- Tasks with issues: {sum(bool(c.issues) for c in conversions)}",
        "",
    ]

    records = [c.record for c in conversions if c.record is not None and not c.issues]
    if records:
        statuses = Counter(r.document_status.value for r in records)
        categories = Counter(c.category.value for r in records for c in r.conditions)
        roles = Counter(c.role.value for r in records for c in r.conditions)
        operators = Counter(g.operator.value for r in records for g in r.groups)
        lines += ["## Label counts (clean records)", ""]
        for title, counter in (
            ("Document status", statuses),
            ("Category", categories),
            ("Role", roles),
            ("Group operator", operators),
        ):
            lines += [f"| {title} | Count |", "|---|---:|"]
            lines += [f"| {k} | {v} |" for k, v in sorted(counter.items())] or ["| (none) | 0 |"]
            lines.append("")
        lines.append(
            f"Conditions per condition-bearing document: "
            f"{_median([len(r.conditions) for r in records if r.conditions])}"
        )
        lines.append("")

    lines += _pace(conversions, pilot_items)

    problems = [c for c in conversions if c.issues]
    if problems:
        lines += ["## Issues to fix in Label Studio", "", "| Advisory | Code | Ref | Detail |"]
        lines.append("|---|---|---|---|")
        for conv in problems:
            for issue in conv.issues:
                detail = issue.message.replace("|", "\\|")
                lines.append(
                    f"| {conv.advisory_id} | {issue.code} | {issue.ref or ''} | {detail} |"
                )
        lines.append("")
    noted = [c for c in conversions if c.notes]
    if noted:
        lines += ["## Notes (informational)", ""]
        lines += [f"- {c.advisory_id}: {'; '.join(c.notes)}" for c in noted]
        lines.append("")
    return "\n".join(lines)


def _median(values: Sequence[float]) -> str:
    return f"{statistics.median(values):.1f}" if values else "n/a"


def _pace(
    conversions: Sequence[Conversion], pilot_items: Mapping[str, Mapping[str, Any]]
) -> list[str]:
    timed = [c for c in conversions if c.lead_time is not None]
    if not timed:
        return ["## Pace", "", "No lead times recorded.", ""]
    minutes = [(c.lead_time or 0.0) / 60 for c in timed]
    lines = [
        "## Pace (Label Studio lead time)",
        "",
        f"- Timed tasks: {len(timed)}",
        f"- Median minutes per document: {_median(minutes)}",
        f"- Total hours: {sum(minutes) / 60:.1f}",
    ]
    per_100 = [
        (c.lead_time or 0.0) / 60 / max(int(pilot_items[c.advisory_id]["words"]), 1) * 100
        for c in timed
        if c.advisory_id in pilot_items
    ]
    if per_100:
        lines.append(f"- Median minutes per 100 words: {_median(per_100)}")
    by_stratum: dict[str, list[float]] = {}
    for c in timed:
        stratum = str(pilot_items.get(c.advisory_id, {}).get("stratum", "unknown"))
        by_stratum.setdefault(stratum, []).append((c.lead_time or 0.0) / 60)
    for stratum, values in sorted(by_stratum.items()):
        lines.append(f"- Median minutes, {stratum} stratum: {_median(values)} (n={len(values)})")
    lines.append("")
    return lines


def load_export(path: Path) -> list[dict[str, Any]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise ValueError("expected a Label Studio JSON export (a list of tasks)")
    return data
