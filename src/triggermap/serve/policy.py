"""Review policy: calibrated confidences and the rules that route items to human review.

A condition is marked *review required* when any of these holds:
- its calibrated confidence is below the accept threshold (or no threshold exists yet);
- its role is one the policy always reviews (exceptions, non-requirements, uncertain);
- negation or exception wording sits in or just before the span;
- it comes from a workaround or mitigation section.
Unresolved groups and unsupported documents are always flagged. The policy file is
versioned and its version travels with every result.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import yaml
from pydantic import BaseModel, ConfigDict, Field

from triggermap.eval.calibration import Calibrator
from triggermap.schema.models import DocumentStatus, Extraction, GroupOperator
from triggermap.text.markdown import BlockKind
from triggermap.text.preprocessing import PreprocessedDocument

DEFAULT_NEGATIONS = [
    "not", "no", "never", "without", "unless", "except", "regardless", "even", "n't", "neither",
    "nor", "unauthenticated", "unaffected",
]  # fmt: skip


class Triggers(BaseModel):
    model_config = ConfigDict(extra="forbid")

    roles: list[str] = Field(default_factory=lambda: ["EXCEPTION", "NOT_REQUIRED", "UNCERTAIN"])
    negation_words: list[str] = Field(default_factory=lambda: list(DEFAULT_NEGATIONS))
    negation_window_words: int = 3
    workaround_sections: bool = True


class ReviewPolicy(BaseModel):
    model_config = ConfigDict(extra="forbid")

    version: str
    model_id: str
    calibration: dict[str, Any] = Field(default_factory=lambda: {"method": "identity"})
    accept_threshold: float | None = None  # None: nothing is accepted without review
    target_precision: float = 0.95
    min_coverage: float = 0.5
    measured: dict[str, Any] = Field(default_factory=dict)
    triggers: Triggers = Field(default_factory=Triggers)

    def calibrator(self) -> Calibrator:
        return Calibrator.from_dict(self.calibration)


def load_policy(path: Path) -> ReviewPolicy:
    return ReviewPolicy.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")))


def save_policy(policy: ReviewPolicy, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Review policy: generated by `triggermap calibrate`; edit triggers by hand if needed.\n"
        "# Thresholds are chosen on the dev calibration half, never on test.\n"
    )
    body = yaml.safe_dump(policy.model_dump(mode="json"), sort_keys=False, allow_unicode=True)
    path.write_text(header + body, encoding="utf-8")


_WORD = re.compile(r"[A-Za-z']+")
_WORKAROUND = re.compile(r"workaround|mitigat|remediat", re.IGNORECASE)


def _section(doc: PreprocessedDocument, position: int) -> str:
    heading = ""
    for block in doc.canonical.blocks:
        if block.start > position:
            break
        if block.kind is BlockKind.HEADING:
            heading = doc.text[block.start : block.end]
    return heading


def apply_policy(
    extraction: Extraction, doc: PreprocessedDocument, policy: ReviewPolicy
) -> Extraction:
    calibrate = policy.calibrator()
    negations = {w.lower() for w in policy.triggers.negation_words}
    conditions = []
    flags: list[str] = [f for f in extraction.review_flags if not f.startswith("low_confidence:")]
    for cond in extraction.conditions:
        raw = cond.confidence if cond.confidence is not None else 1.0
        calibrated = round(calibrate(raw), 4)
        conditions.append(cond.model_copy(update={"confidence": calibrated}))
        reasons = []
        if policy.accept_threshold is None:
            reasons.append("uncalibrated")
        elif calibrated < policy.accept_threshold:
            reasons.append("low_confidence")
        if cond.role.value in policy.triggers.roles:
            reasons.append(f"role_{cond.role.value.lower()}")
        before = _WORD.findall(doc.text[max(0, cond.span[0] - 60) : cond.span[0]])
        window = before[-policy.triggers.negation_window_words :]
        inside = _WORD.findall(doc.text[cond.span[0] : cond.span[1]])
        if any(w.lower() in negations for w in window + inside):
            reasons.append("negation")
        if policy.triggers.workaround_sections and _WORKAROUND.search(_section(doc, cond.span[0])):
            reasons.append("workaround_section")
        flags += [f"review_required:{cond.id}:{reason}" for reason in reasons]
    if extraction.document_status is DocumentStatus.UNSUPPORTED_STRUCTURE:
        flags.append("review_required:document:unsupported_structure")
    if any(g.operator is GroupOperator.UNRESOLVED for g in extraction.groups):
        flags.append("review_required:groups:unresolved")
    flags.append(f"review_policy:{policy.version}")
    return extraction.model_copy(
        update={"conditions": tuple(conditions), "review_flags": tuple(dict.fromkeys(flags))}
    )
